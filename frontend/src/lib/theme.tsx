// ─── Provider ────────────────────────────────────────────────────────────────

interface ThemeCtx {
  theme: ThemeSettings;
  setThemeLocal: (t: ThemeSettings) => void;   // live preview, not persisted
  reload: () => Promise<void>;
}

const Ctx = createContext<ThemeCtx>({
  theme: DEFAULT_THEME,
  setThemeLocal: () => {},
  reload: async () => {},
});

export function ThemeProvider({ children }: { children: ReactNode }) {
  const { user } = useAuth();
  const [theme, setTheme] = useState<ThemeSettings>(DEFAULT_THEME);

  const reload = useCallback(async () => {
    try {
      const { theme: saved } = await api.getThemeSettings();
      const merged = mergeTheme(saved as Partial<ThemeSettings> | null);
      setTheme(merged);
      applyTheme(merged);
    } catch { /* keep current theme on failure */ }
  }, []);

  useEffect(() => {
    if (user) void reload();
  }, [user, reload]);

  const setThemeLocal = useCallback((t: ThemeSettings) => {
    setTheme(t);
    applyTheme(t);
  }, []);

  return <Ctx.Provider value={{ theme, setThemeLocal, reload }}>{children}</Ctx.Provider>;
}

export function useTheme() {
  return useContext(Ctx);
}
