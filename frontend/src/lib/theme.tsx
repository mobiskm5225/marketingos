export function applyTheme(theme: ThemeSettings): void {
  const root = document.documentElement;
  for (const [cssVar, value] of Object.entries(theme.vars)) {
    root.style.setProperty(cssVar, value);
  }
  document.body.style.fontSize = `${theme.baseFontSize}px`;
}

export function mergeTheme(saved: Partial<ThemeSettings> | null): ThemeSettings {
  if (!saved) return DEFAULT_THEME;
  return {
    vars: { ...DEFAULT_THEME.vars, ...(saved.vars ?? {}) },
    workspaceName: saved.workspaceName || DEFAULT_THEME.workspaceName,
    markLetter: (saved.markLetter || DEFAULT_THEME.markLetter).slice(0, 2),
    baseFontSize: saved.baseFontSize || DEFAULT_THEME.baseFontSize,
    guidelines: { ...DEFAULT_GUIDELINES, ...(saved.guidelines ?? {}) },
  };
}

// ─── Export formats — "usable everywhere" ────────────────────────────────────

export function exportAsCss(theme: ThemeSettings): string {
  const lines = Object.entries(theme.vars).map(([k, v]) => `  ${k}: ${v};`);
  return `:root {\n${lines.join('\n')}\n}\nbody { font-size: ${theme.baseFontSize}px; }`;
}

// W3C Design Tokens Community Group format (2025.10)
export function exportAsW3cTokens(theme: ThemeSettings): string {
  const v = theme.vars;
  const color = (val: string) => ({ $type: 'color', $value: val });
  const dim   = (val: string) => ({ $type: 'dimension', $value: val });
  const tokens = {
    color: {
      brand: {
        'primary-action': color(v['--sn-accent']),
        'accent':         color(v['--sn-green']),
        'header':         color(v['--sn-top']),
        'rail':           color(v['--sn-rail']),
        'link':           color(v['--sn-link']),
      },
      surface: {
        'background': color(v['--sn-bg']),
        'panel':      color(v['--sn-panel']),
        'border':     color(v['--sn-border']),
      },
      text: {
        'body':  color(v['--sn-text']),
        'muted': color(v['--sn-muted']),
      },
      status: {
        'info':    color(v['--sn-blue']),
        'warning': color(v['--sn-orange']),
        'danger':  color(v['--sn-red']),
        'success': color(v['--sn-green']),
      },
    },
    dimension: {
      'radius-control': dim(v['--sn-radius']),
      'radius-card':    dim(v['--sn-radius-lg']),
      'font-size-base': dim(`${theme.baseFontSize}px`),
    },
    fontFamily: {
      'sans': { $type: 'fontFamily', $value: v['--sn-font'] },
      'mono': { $type: 'fontFamily', $value: v['--sn-mono'] },
    },
  };
  return JSON.stringify(tokens, null, 2);
}

